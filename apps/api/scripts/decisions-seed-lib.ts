// The seed of the decisions table (slice 2.2, decision 191): every entry of
// `docs/planning/decisions.md`, imported as an active decision whose origin is the log and whose
// reference is the entry's number. Pure functions, so they are tested without a database.

export interface LogEntry {
  number: number;
  /** The entry's date, `YYYY-MM-DD`. */
  date: string;
  decision: string;
  reason: string;
}

const ROW = /^\| (\d+) \| (\d{4}-\d{2}-\d{2}) \| (.*) \| (.*) \|$/;

/** The entries of the log's table, in order. Lines that are not entries are skipped. */
export function parseLog(markdown: string): LogEntry[] {
  const entries: LogEntry[] = [];
  for (const line of markdown.split("\n")) {
    const match = ROW.exec(line.trimEnd());
    if (match === null) continue;
    const [, number, date, decision, reason] = match;
    if (
      number === undefined ||
      date === undefined ||
      decision === undefined ||
      reason === undefined
    ) {
      continue;
    }
    entries.push({
      number: Number(number),
      date,
      decision: decision.trim(),
      reason: reason.trim(),
    });
  }
  return entries;
}

/**
 * The entries an entry says it replaces ("Replaces 136 and 137", "Replaces 139 and 153"): those
 * are imported as superseded. "Refines" and "Changes" do not replace.
 */
export function replacedBy(entries: readonly LogEntry[]): Map<number, number> {
  const replaced = new Map<number, number>();
  for (const entry of entries) {
    for (const match of entry.decision.matchAll(/\bReplaces ((?:\d+)(?:(?:, | and )\d+)*)/g)) {
      for (const number of (match[1] ?? "").split(/, | and /)) {
        replaced.set(Number(number), entry.number);
      }
    }
  }
  return replaced;
}

/** A SQL string literal. */
function literal(text: string): string {
  return `'${text.replaceAll("'", "''")}'`;
}

/**
 * A migration that imports `entries`: each once (`on conflict do nothing`), active unless a
 * later entry of the whole log replaces it. Entries already imported by an earlier seed are
 * left out by the caller.
 */
export function seedMigration(entries: readonly LogEntry[], all: readonly LogEntry[]): string {
  const replaced = replacedBy(all);
  const rows = entries.map((entry) => {
    const status = replaced.has(entry.number) ? "superseded" : "active";
    return (
      `  (${String(entry.number)}, ${literal(entry.decision)}, ${literal(entry.reason)}, ${literal(status)}, ` +
      `'the owner', ${literal(`${entry.date}T00:00:00Z`)}, 'import', ${literal(String(entry.number))})`
    );
  });
  return [
    "-- Generated by `pnpm decisions:seed` from docs/planning/decisions.md (decision 191): the log's",
    "-- entries as decisions, numbered as in the log, active unless a later entry replaces them.",
    "-- Do not edit by hand.",
    "insert into public.decisions",
    "  (number, statement, reason, status, decided_by_name, decided_at, origin, origin_ref)",
    "overriding system value",
    "values",
    rows.join(",\n"),
    "on conflict (origin, origin_ref) where origin_ref is not null do nothing;",
    "",
  ].join("\n");
}

/** The entry numbers an existing seed migration imports. */
export function seededNumbers(sql: string): Set<number> {
  const numbers = new Set<number>();
  for (const match of sql.matchAll(/'import', '(\d+)'\)/g)) numbers.add(Number(match[1]));
  return numbers;
}
