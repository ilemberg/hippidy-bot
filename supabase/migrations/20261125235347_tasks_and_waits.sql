-- Slice 3.3, part A (decision 210; `docs/planning/slice-3-3.md`): the built-in tracker's tasks
-- and their history, the waiting-on list, and the task a thread works on. Additive only
-- (decision 86).

create table public.tasks (
  id uuid primary key default gen_random_uuid(),
  -- Its key is `T-<number>`.
  number bigint generated by default as identity unique,
  source text not null check (source in ('slack', 'ui')),
  workspace_id text not null,
  title text not null check (char_length(title) between 1 and 200),
  description text check (description is null or char_length(description) <= 4000),
  status text not null default 'todo' check (status in ('todo', 'doing', 'done')),
  assignee_actor_id text,
  assignee_name text,
  version integer not null default 1 check (version >= 1),
  created_by_actor_id text not null,
  created_by_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  search tsvector generated always as (
    to_tsvector('english', title || ' ' || coalesce(description, ''))
  ) stored
);

create index tasks_list_idx on public.tasks (source, workspace_id, status, updated_at desc);
create index tasks_search_idx on public.tasks using gin (search);

create table public.task_events (
  id uuid primary key default gen_random_uuid(),
  task_id uuid not null references public.tasks (id) on delete cascade,
  kind text not null check (kind in ('created', 'edited')),
  actor_id text not null,
  actor_name text,
  before jsonb,
  after jsonb not null,
  at timestamptz not null default now(),
  seq bigint generated always as identity
);

create index task_events_task_idx on public.task_events (task_id, seq);

create table public.waits (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity unique,
  source text not null check (source in ('slack', 'ui')),
  workspace_id text not null,
  waiter_actor_id text not null,
  waiter_name text,
  waiting_on_actor_id text not null,
  waiting_on_name text,
  what text not null check (char_length(what) between 1 and 300),
  -- A task's key in the provider, as given: `T-12` or `SCRUM-8`.
  task_key text check (task_key is null or char_length(task_key) <= 30),
  conversation_id uuid references public.conversations (id) on delete set null,
  recorded_by_actor_id text not null,
  recorded_by_name text,
  ended_by_actor_id text,
  ended_by_name text,
  ended_at timestamptz,
  check ((ended_at is null) = (ended_by_actor_id is null)),
  -- The `record_wait` call that wrote it: each call writes once.
  custom_tool_use_id text unique,
  created_at timestamptz not null default now()
);

create index waits_open_idx on public.waits (source, workspace_id, created_at desc)
  where ended_at is null;
create index waits_people_idx on public.waits (waiting_on_actor_id, waiter_actor_id);
create index waits_conversation_idx on public.waits (conversation_id)
  where conversation_id is not null;
create index waits_task_idx on public.waits (task_key) where task_key is not null;

-- The task a thread works on (SCRUM-8), as its key in the provider, and when it was linked.
alter table public.conversations
  add column task_key text check (task_key is null or char_length(task_key) <= 30),
  add column task_linked_at timestamptz;

create index conversations_task_idx on public.conversations (task_key)
  where task_key is not null;

alter table public.tasks enable row level security;
alter table public.task_events enable row level security;
alter table public.waits enable row level security;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on public.tasks, public.task_events, public.waits from anon, authenticated;
  end if;
end
$$;
