-- Slice 3.2, part A (decision 208; `docs/planning/slice-3-2.md`): conflicts, and who alone may
-- decide a proposal that replaces someone else's decision. Additive only (decision 86).

-- Who may confirm or reword a guarded proposal: fixed when it is recorded (the owner of the
-- replaced decision's area, else the fallback, and the replaced decision's own decider). Null
-- for a proposal anyone in its thread may act on, as before.
alter table public.decisions
  add column deciders text[];

create table public.conflicts (
  id uuid primary key default gen_random_uuid(),
  -- The number people cite it by, like a decision's.
  number bigint generated by default as identity unique,
  source text not null check (source in ('slack', 'ui')),
  workspace_id text not null,
  -- `replacement`: a proposal that replaces someone else's decision; `raised`: the teammate
  -- raised it; `capture`: listening proposed a replacement.
  kind text not null check (kind in ('replacement', 'raised', 'capture')),
  summary text not null check (char_length(summary) between 1 and 600),
  -- Where it came up: a thread the bot is in, or a listened channel's thread.
  conversation_id uuid references public.conversations (id) on delete set null,
  channel_id text,
  thread_id text,
  -- The area it is in, as a label, like a decision's.
  area text check (area is null or char_length(area) between 1 and 100),
  -- The active decisions it bears on, and the proposal that would replace one, if any.
  decision_ids uuid[] not null default '{}' check (cardinality(decision_ids) <= 3),
  proposal_id uuid references public.decisions (id) on delete set null,
  -- Who wants what: [{ actorId, name, says }], at most four.
  positions jsonb not null default '[]'::jsonb check (jsonb_typeof(positions) = 'array'),
  -- Who decides it, fixed when it is recorded; empty when nobody is set to.
  deciders text[] not null default '{}',
  status text not null default 'open' check (status in ('open', 'settled')),
  outcome text check (outcome in ('kept', 'changed', 'dismissed')),
  note text check (note is null or char_length(note) <= 500),
  settled_by_actor_id text,
  settled_by_name text,
  settled_at timestamptz,
  check ((status = 'open') = (outcome is null) and (status = 'open') = (settled_at is null)),
  -- The tool call that raised it: each call raises once.
  custom_tool_use_id text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index conflicts_open_idx on public.conflicts (source, workspace_id, status, created_at desc);
create index conflicts_conversation_idx on public.conflicts (conversation_id)
  where conversation_id is not null;
create unique index conflicts_proposal_idx on public.conflicts (proposal_id)
  where proposal_id is not null;
create index conflicts_decisions_idx on public.conflicts using gin (decision_ids);

alter table public.conflicts enable row level security;

do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on public.conflicts from anon, authenticated;
  end if;
end
$$;
